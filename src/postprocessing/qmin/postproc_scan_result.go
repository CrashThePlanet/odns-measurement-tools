// get the metadata from the metadata.json file
func getMetadataFromFile(path string) (*Metadata, error) {
	jsonFile, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("Could not open metadata file: %w", err)
	}
	defer jsonFile.Close()

	bytes, err := io.ReadAll(jsonFile)
	if err != nil {
		return nil, fmt.Errorf("Could not read metadata file: %w", err)
	}

	var metadata Metadata

	err = json.Unmarshal(bytes, &metadata)
	if err != nil {
		return nil, fmt.Errorf("Could not parse JSON file: %w", err)
	}

	return &metadata, nil
}

// process a single results.parquet file
func processFile(dirPath string, res1 map[string]ScanResultResolver, res2 map[string]ScanResolverPair, dbASN *maxminddb.Reader, dbLoc *maxminddb.Reader, pattern_matching bool) *Metadata {

	file, err := os.Open(dirPath + "/result.parquet")
	if err != nil {
		log.Fatalln("Error opening file: ", err.Error())
	}
	defer file.Close()
	if !strings.HasSuffix(file.Name(), ".parquet") {
		log.Fatalln("Input file has to be a .parquet file")
	}

	metadata, err := getMetadataFromFile(dirPath + "/metadata.json")
	if err != nil {
		log.Fatalln(err)
	}

	reader := parquet.NewGenericReader[qmin_scanner.ParquetQueryResult](file)
	defer reader.Close()

	// read a chunk of 128 rows at a time so we dont have to load the entire file into ram
	rows := make([]qmin_scanner.ParquetQueryResult, 128)
	for {
		n, err := reader.Read(rows)
		if err != nil && err != io.EOF {
			log.Fatalln("Error while reading parquet file: ", err.Error())
		}
		if n == 0 && err == io.EOF {
			break
		}

		for i := 0; i < n; i++ {
			r1, r2 := evalRow(rows[i], dbASN, dbLoc, metadata, pattern_matching)
			if tmp, ok := res1[metadata.Protocol+r1.Queried_IP]; ok {
				res1[metadata.Protocol+r1.Queried_IP] = combineResults(tmp, r1)
			} else {
				res1[metadata.Protocol+r1.Queried_IP] = r1
			}
			if r2 != nil {
				if tmp, ok := res2[metadata.Protocol+r2.Queried_IP+r2.RequestingIP]; ok {
					res2[metadata.Protocol+r2.Queried_IP+r2.RequestingIP+r2.QMIN_pattern] = combineResultsPair(tmp, *r2)
				} else {
					res2[metadata.Protocol+r2.Queried_IP+r2.RequestingIP+r2.QMIN_pattern] = *r2
				}
			}
		}
	}
	return metadata
}

type dirData struct {
	path string
	info os.DirEntry
}

func getValidInputDirectories(basePath string) ([]dirData, error) {
	directories := []dirData{}

	err := filepath.WalkDir(basePath, func(path string, info os.DirEntry, err error) error {
		if !info.IsDir() {
			return nil
		}
		if _, err := os.Stat(path + "/result.parquet"); errors.Is(err, os.ErrNotExist) {
			return nil
		}
		if _, err := os.Stat(path + "/metadata.json"); errors.Is(err, os.ErrNotExist) {
			return nil
		}
		directories = append(directories, dirData{path, info})
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("Failed to get subdirectories: %w", err)
	}

	return directories, nil
}

func startFileProcessing(inputPath string, outputPath string, dbASN *maxminddb.Reader, dbCountry *maxminddb.Reader, pattern_matching bool, combine bool) {
	// these will hold the processed data
	resolver1 := make(map[string]ScanResultResolver)
	resolver2 := make(map[string]ScanResolverPair)

	if combine {
		dirs, err := getValidInputDirectories(inputPath)
		if err != nil {
			log.Println(err)
			return
		}
		for _, dir := range dirs {
			fmt.Println("Now processing: ", dir.path)
			processFile(dir.path, resolver1, resolver2, dbASN, dbCountry, pattern_matching)
		}
	} else {
		if _, err := os.Stat(inputPath + "/result.parquet"); errors.Is(err, os.ErrNotExist) {
			fmt.Println("results.parquet file doesnt exists in \"" + inputPath + "\" (skipping)")
			return
		}
		if _, err := os.Stat(inputPath + "/metadata.json"); errors.Is(err, os.ErrNotExist) {
			fmt.Println("metadata.json file doesnt exists in \"" + inputPath + "\" (skipping)")
			return
		}
		fmt.Println("Now processing: ", inputPath)
		m := processFile(inputPath, resolver1, resolver2, dbASN, dbCountry, pattern_matching)
		// writing metadata of scan to output directory
		metadataJSON, err := json.Marshal(m)
		if err != nil {
			log.Println("Could not convert metadata to struct: skipping")
		} else {
			os.WriteFile(outputPath+"/scan_metadata.json", metadataJSON, 0644)
		}
	}

	if err := parquet.WriteFile(outputPath+"/test1.parquet", slices.Collect(maps.Values(resolver1))); err != nil {
		log.Fatalln("Error writing output Parquet file 1: ", err.Error())
	}

	if err := parquet.WriteFile(outputPath+"/test2.parquet", slices.Collect(maps.Values(resolver2))); err != nil {
		log.Fatalln("Error writing output Parquet file 2: ", err.Error())
	}
}

