// transform the scan pattern to the pattern format from the papers and extract min/max (according to the qmin rfc) rule estimations
// a scan pattern might look like this: 23.22.21.20.19.18.17.16.15.14.13.12.11.10.9.8.7.6.5.4_TXT|3_NS|2_NS|1_NS|*ip*-24-645_NS
func analyzePattern(pattern string, metadata *Metadata) (qmin bool, qmin_pattern string, max int, min int) {
	// how many labels has the used base domain
	baseDomainLabelCount := 0
	if strings.HasSuffix(metadata.BaseURL, ".") {
		baseDomainLabelCount = strings.Count(metadata.BaseURL, ".")
	} else {
		baseDomainLabelCount = strings.Count(metadata.BaseURL, ".") + 1
	}

	// no qmin behaviour
	if !strings.Contains(pattern, "|") {
		// weird patterns with only a single label
		if !strings.Contains(pattern, ".") {
			return false, pattern, 0, 0
		}
		// split into the observed labels and the used Record type
		// record type will (most likely) be TXT
		pat_split := strings.Split(pattern, "_")
		if len(pat_split) < 2 {
			log.Fatalln("Malformed pattern:", pattern)
		}
		// with label depth of 24 and 2 label base domain return wil be "26TXT"
		return false, strconv.Itoa(strings.Count(pattern, ".")+1+baseDomainLabelCount) + pat_split[1], 1, 1
	}
	qmin = true
	qmin_pattern = ""
	max = strings.Count(pattern, "|") + 1
	min = 0
	// minimzed boundary defines how many labels are handled using primitive QMIN (see RFC 9156)
	min_boundary_reached := false
	parts := strings.Split(pattern, "|")
	slices.Reverse(parts)
	for _, part := range parts {
		// counting the dots "." is equivilant to counting the labels within a part (#labels = #dots + 1)
		if !min_boundary_reached && strings.Count(part, ".") == 0 {
			min++
		} else {
			min_boundary_reached = true
		}
		// see above
		split1 := strings.Split(part, "_")
		split2 := strings.Split(split1[0], ".")

		// handle the ID label (first one)
		if len(split2) == 1 && strings.Contains(split2[0], "-") {
			qmin_pattern = strconv.Itoa(1+baseDomainLabelCount) + split1[1]
			continue
		}
		//everything else
		stage, err := strconv.Atoi(split2[0])
		if err != nil {
			fmt.Println(part)
			log.Fatalln("error converting string to int: ", err.Error())
		}
		// needs to add 1 because of the id label
		qmin_pattern = strconv.Itoa(stage+1+baseDomainLabelCount) + split1[1] + "-" + qmin_pattern
	}
	return
}

// evaluates one row from the scan results
func evalRow(row qmin_scanner.ParquetQueryResult, ASNDB *maxminddb.Reader, CountryDB *maxminddb.Reader, metadata *Metadata, pattern_matching bool) (r1 ScanResultResolver, r2 *ScanResolverPair) {
	r1.Queried_IP = row.ResolverIP

	// lokkup queried IP in maxmind DBs
	var asnR ASNRecord
	var cR CountryRecord

	ip := netip.MustParseAddr(row.ResolverIP)

	err := ASNDB.Lookup(ip).Decode(&asnR)
	if err != nil {
		log.Fatalln("error getting record: ", err)
	}

	err = CountryDB.Lookup(ip).Decode(&cR)
	if err != nil {
		log.Fatalln("error getting record: ", err)
	}
	r1.Count = 1

	r1.Protocol = metadata.Protocol
	r1.Queried_IP_ASN = asnR.Number
	r1.Queried_IP_Org = asnR.Organization
	r1.Queried_IP_Country = cR.Country.ISOCode
	r1.Resolver_Type = row.ResolverType
	r1.QMIN_enabled = TriBool(Nil)
	r1.Induction_QMIN = TriBool(Nil)
	r1.Nx_optimization = TriBool(Nil)
	r1.Errors = make(map[string]int)

	// reuqesting IP is NONE if we get and error from the resolver
	// this can happen if an error occurs or when testing is related to NXDOMAIN responses
	// eg: NXDOMAIN Optimization, QMIN Mode testing
	if row.RequestingIP == "NONE" {
		if row.ModeCheck && row.Response == "nxdomain" {
			r1.Qmin_mode = "strict"
		} else if row.NXCheck {
			r1.Nx_optimization = TriBool(row.NxOptimization)
		} else {
			r1.Errors[row.Response] = 1
		}
		return r1, nil
	}
	r1.RequestingIPs = []string{row.RequestingIP}

	// if QMIN mode checking flag is set
	if row.ModeCheck {
		// the strict case has been handled above
		// only the relaxed case remains
		// if neither is true the resolver also doesnt use QMIN and this field carried no relevant information
		if strings.Contains(row.Response, "|") {
			r1.Qmin_mode = "relaxed"
		}
		return r1, nil
	}
	// checking for NCDOMAIN optimization
	// --> intermideate negative response caching
	if row.NXCheck {
		// is already evaluated during scanning -> just copy value
		r1.Nx_optimization = TriBool(row.NxOptimization)
		return r1, nil
	}
	// check for QMIN behaviour for domain resolutions caused by CNAME records
	if row.InducedQMINCheck {
		if strings.Contains(row.InducedRes, "|") {
			r1.Induction_QMIN = TriBool(True)
		} else {
			r1.Induction_QMIN = TriBool(False)
		}
		return r1, nil
	}
	// if nothing above is the case we evaluate are evaluating for normal QMIN bahviour
	qmin, pat, max, min := analyzePattern(row.Response, metadata)

	// get information about the IP that is requesting data at the DNS server
	ip, err = netip.ParseAddr(row.RequestingIP)
	if err != nil {
		log.Println("Malformed IP, skipping row: ", err.Error())
		return r1, nil
	}

	err = ASNDB.Lookup(ip).Decode(&asnR)
	if err != nil {
		log.Fatalln("error getting record: ", err)
	}

	err = CountryDB.Lookup(ip).Decode(&cR)
	if err != nil {
		log.Fatalln("error getting record: ", err)
	}
	// match pattern against known pattern
	match := []string{"unset"}
	if pattern_matching {
		if m, ok := knownResolverPattern[pat]; ok {
			match = m
		} else {
			match = []string{"none"}
		}
	}

	r2 = &ScanResolverPair{
		Queried_IP:             r1.Queried_IP,
		Queried_IP_Org:         r1.Queried_IP_Org,
		Queried_IP_ASN:         r1.Queried_IP_ASN,
		Queried_IP_Country:     r1.Queried_IP_Country,
		QMIN_enabled:           qmin,
		QMIN_pattern:           pat,
		Max_min_rfc_9156:       strconv.Itoa(max) + "-" + strconv.Itoa(min),
		Count:                  1,
		RequestingIP:           row.RequestingIP,
		Requesting_IP_ASN:      asnR.Number,
		Requesting_IP_Org:      asnR.Organization,
		Requesting_IP_Country:  cR.Country.ISOCode,
		Resolver_Type:          row.ResolverType,
		Protocol:               metadata.Protocol,
		Resolver_pattern_match: match,
	}
	if qmin {
		r1.QMIN_enabled = TriBool(True)
	} else {
		r1.QMIN_enabled = TriBool(False)
	}
	return r1, r2
}

// as evalrow only analyses one row we now have to combine each single evaluated row
// each row might carry different information regarding one resolver (eg QMIN behaviour, NXDOMAIN optimization, ...)
func combineResults(r1 ScanResultResolver, r2 ScanResultResolver) (res ScanResultResolver) {
	if len(r2.RequestingIPs) >= 1 && !slices.Contains(r1.RequestingIPs, r2.RequestingIPs[0]) {
		r1.RequestingIPs = append(r1.RequestingIPs, r2.RequestingIPs[0])
	}

	// this is qhere the TriBool comes in
	// one resolver can behave differently between two requests (eg. doing QMIN in one request and not in the other)
	// therefore the TriBool has a state "Uncertain" which basicly means that we have observed both

	if r1.QMIN_enabled == TriBool(Nil) {
		r1.QMIN_enabled = r2.QMIN_enabled
	} else {
		if r2.QMIN_enabled != TriBool(Nil) {
			if r1.QMIN_enabled != r2.QMIN_enabled {
				r1.QMIN_enabled = TriBool(Uncertain)
			}
		}
	}

	if r1.Induction_QMIN == TriBool(Nil) {
		r1.Induction_QMIN = r2.Induction_QMIN
	} else {
		if r2.Induction_QMIN != TriBool(Nil) {
			if r1.Induction_QMIN != r2.Induction_QMIN {
				r1.Induction_QMIN = TriBool(Uncertain)
			}
		}
	}

	if r1.Nx_optimization == TriBool(Nil) {
		r1.Nx_optimization = r2.Nx_optimization
	} else {
		if r2.Nx_optimization != TriBool(Nil) {
			if r1.Nx_optimization != r2.Nx_optimization {
				r1.Nx_optimization = TriBool(Uncertain)
			}
		}
	}

	// same with tribool but thet states are either "strict" or "relaxed", so we set "both" if we seen both
	if r1.Qmin_mode == "" {
		r1.Qmin_mode = r2.Qmin_mode
	} else {
		if r2.Qmin_mode != "" && r1.Qmin_mode != r2.Qmin_mode {
			r1.Qmin_mode = "both"
		}
	}
	// combine errors
	if len(r2.Errors) > 0 {
		for k, v := range r2.Errors {
			r1.Errors[k] += v
		}
	}

	r1.Count++

	return r1
}

